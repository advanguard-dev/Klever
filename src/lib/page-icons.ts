export const PAGE_ICON_NAMES = Object.keys(PAGE_ICONS);

export function lookupPageIcon(name: string): LucideIcon | undefined {
  return PAGE_ICONS[toKebab(name)];
}

export function filterPageIcons(query: string): string[] {
  const q = toKebab(query);
  if (!q) return PAGE_ICON_NAMES;
  const compact = q.replace(/-/g, "");
  return PAGE_ICON_NAMES.filter((n) => n.includes(q) || n.replace(/-/g, "").includes(compact));
}
