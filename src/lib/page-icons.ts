/** Frontmatter value: `lucide:file-text`. Emoji and short marks stay unprefixed. */
export const LUCIDE_PREFIX = "lucide:";

export function isLucideIcon(icon?: string): boolean {
  return Boolean(icon?.startsWith(LUCIDE_PREFIX));
}

export function toKebab(name: string): string {
  return name
    .trim()
    .replace(/^lucide:/i, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

export function lucideIconName(icon: string): string {
  return toKebab(icon.startsWith(LUCIDE_PREFIX) ? icon.slice(LUCIDE_PREFIX.length) : icon);
}

export function lucideIconValue(name: string): string {
  return `${LUCIDE_PREFIX}${toKebab(name)}`;
}

